 await page.locator('.game__overlay button').click();
 await page.locator('.game__countdown').waitFor({ state: 'visible' });
 await page.locator('.game__countdown').waitFor({ state: 'hidden' });
 await page.locator('.game').screenshot({ path: `${out}/06-game-desktop.png`, animations: 'disabled' });
 await page.goto('http://127.0.0.1:4322/proyectos/pseudo-riemannian-gnn/', { waitUntil: 'networkidle' });
 await page.locator('astro-island[component-url*="ThesisExplorer"]').scrollIntoViewIfNeeded();
 await page.locator('.thesis-explorer canvas').first().waitFor();
 await page.locator('astro-dev-toolbar').evaluateAll(els => els.forEach(el => el.remove()));
 await page.locator('.thesis-explorer').screenshot({ path: `${out}/07-thesis.png`, animations: 'disabled' });
 const mobileContext = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true, colorScheme: 'light', reducedMotion: 'reduce' });
 const mobilePage = await mobileContext.newPage();
 await mobilePage.goto('http://127.0.0.1:4322/', { waitUntil: 'networkidle' });
 await mobilePage.locator('astro-dev-toolbar').evaluateAll(els => els.forEach(el => el.remove()));
 await mobilePage.screenshot({ path: `${out}/02-home-mobile.png`, animations: 'disabled', timeout: 60000 });
 await mobilePage.setViewportSize({ width: 320, height: 700 });
 await mobilePage.locator('.nav').screenshot({ path: `${out}/10-nav-mobile.png` });
 await mobilePage.setViewportSize({ width: 390, height: 844 });
