 await page.locator('#terminal-mode').screenshot({ path: `${out}/05-terminal.png`, animations: 'disabled' });
 await page.keyboard.press('Escape');
 await page.locator('.game__canvas').scrollIntoViewIfNeeded();
 await page.waitForFunction(() => !document.querySelector('astro-island[component-url*="F1Game"]')?.hasAttribute('ssr'));
